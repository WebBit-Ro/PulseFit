document.querySelectorAll(".faq-item button").forEach((button) => {
  button.addEventListener("click", () => {
    const currentItem = button.closest(".faq-item");
    const shouldOpen = !currentItem.classList.contains("open");

    document.querySelectorAll(".faq-item").forEach((item) => {
      item.classList.remove("open");
      item.querySelector("button").setAttribute("aria-expanded", "false");
      item.querySelector(".faq-symbol").textContent = "+";
      item.querySelector(".faq-answer").hidden = true;
    });

    if (shouldOpen) {
      currentItem.classList.add("open");
      button.setAttribute("aria-expanded", "true");
      currentItem.querySelector(".faq-symbol").textContent = "−";
      currentItem.querySelector(".faq-answer").hidden = false;
    }
  });
});

bookingForm.addEventListener("submit", async (event) => {
  event.preventDefault();
  bookingError.hidden = true;

  if (!bookingForm.reportValidity()) return;

  const formData = new FormData(bookingForm);
  const booking = Object.fromEntries(formData.entries());
  const submitButton = bookingForm.querySelector("[type='submit']");
  submitButton.disabled = true;

  try {
    if (bookingEndpoint) {
      const response = await fetch(bookingEndpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(booking)
      });

      if (!response.ok) throw new Error("booking-request-failed");
      bookingSuccess.querySelector("p:not(.eyebrow)").dataset.i18n = "form.sentText";
      bookingSuccess.querySelector("p:not(.eyebrow)").textContent = getValue("form.sentText");
    } else {
      bookingSuccess.querySelector("p:not(.eyebrow)").dataset.i18n = "form.successText";
      bookingSuccess.querySelector("p:not(.eyebrow)").textContent = getValue("form.successText");
    }

    bookingFormView.hidden = true;
    bookingSuccess.hidden = false;
    bookingSuccess.querySelector("button")?.focus();
  } catch {
    bookingError.dataset.i18n = "form.endpointError";
    bookingError.textContent = getValue("form.endpointError");
    bookingError.hidden = false;
  } finally {
    submitButton.disabled = false;
  }
});

