function getValue(path) {
  return path.split(".").reduce((value, key) => value?.[key], translations[currentLanguage]);
}

function applyLanguage(language) {
  if (!translations[language]) return;
  currentLanguage = language;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = getValue(element.dataset.i18n);
    if (typeof value === "string") element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = getValue(element.dataset.i18nAlt);
    if (typeof value === "string") element.alt = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = getValue(element.dataset.i18nPlaceholder);
    if (typeof value === "string") element.placeholder = value;
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  document.querySelectorAll(".menu-toggle").forEach((button) => {
    button.setAttribute("aria-label", getValue(menuIsOpen() ? "common.menuClose" : "common.menuOpen"));
  });

  document.querySelectorAll("[data-open-booking][aria-label]").forEach((button) => {
    const program = button.dataset.program;
    if (program) button.setAttribute("aria-label", `${getValue("common.book")}: ${getValue(`programs.${program}Title`)}`);
  });

  document.title = "PulseFit — " + (language === "en" ? "Personal Training Studio" : language === "ru" ? "Студия персональных тренировок" : "Студія персональних тренувань");
  document.querySelector('meta[name="description"]')?.setAttribute("content", getValue("metaDescription"));

  try {
    localStorage.setItem("pulsefit-language", language);
  } catch {
    return;
  }
}

function menuIsOpen() {
  return menuToggle?.getAttribute("aria-expanded") === "true";
}

function setMenuOpen(open) {
  if (!menuToggle || !mobileMenu) return;
  menuToggle.setAttribute("aria-expanded", String(open));
  menuToggle.setAttribute("aria-label", getValue(open ? "common.menuClose" : "common.menuOpen"));
  mobileMenu.hidden = !open;
}

function localDateValue(date = new Date()) {
  const offset = date.getTimezoneOffset();
  return new Date(date.getTime() - offset * 60000).toISOString().slice(0, 10);
}

function openBooking(program = "") {
  setMenuOpen(false);
  lastFocusedElement = document.activeElement;
  bookingForm.reset();
  bookingFormView.hidden = false;
  bookingSuccess.hidden = true;
  bookingError.hidden = true;
  bookingError.textContent = "";
  dateInput.min = localDateValue();
  if (program) programSelect.value = program;
  if (typeof bookingDialog.showModal === "function") {
    bookingDialog.showModal();
    document.body.classList.add("dialog-open");
  }
  bookingDialog.querySelector(".dialog-close")?.focus();
}

function closeBooking() {
  if (bookingDialog.open) bookingDialog.close();
}

